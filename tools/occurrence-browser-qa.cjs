const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium} = require(process.argv[2]);
(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  const page = await browser.newPage({viewport: {width: 1280, height: 900}});
  const base = 'http://127.0.0.1:8771/tools/occurrence-browser-fixture.php';
  const failures = [];
  page.on('pageerror', error => failures.push(error.message));
  try {
    await page.goto(base + '?view=report&fresh=1');
    assert.equal(await page.locator('select[id^="occurrence-status-"]').count(), 3);
    assert.equal(await page.locator('.elavira-latest-note').count(), 0);
    await page.locator('#occurrence-note-1').fill('First occurrence note');
    await page.locator('#occurrence-status-1').selectOption('addressed');
    await page.locator('#occurrence-status-1').locator('xpath=ancestor::form').getByRole('button', {name:'Save occurrence review'}).click();
    await page.waitForURL('**#elavira-status-notice');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'elavira-status-notice');
    assert.match(await page.locator('[role="status"]').innerText(), /saved/);
    await page.goto(base + '?view=report');
    assert.equal(await page.locator('.elavira-occurrence-addressed').count(), 1);
    assert.equal(await page.locator('.elavira-occurrence-addressed .elavira-latest-note p').innerText(), 'First occurrence note');
    assert.equal(await page.locator('#occurrence-note-1').inputValue(), '');
    assert.equal(await page.locator('.elavira-occurrence-active .elavira-latest-note').count(), 0);
    assert.equal(await page.locator('.elavira-occurrence-active').count(), 2);
    assert.equal(await page.locator('#occurrence-status-2').inputValue(), 'open');
    await page.locator('#occurrence-note-2').fill('Second occurrence note');
    await page.locator('#occurrence-status-2').selectOption('reviewed_not_issue');
    await page.locator('#occurrence-status-2').locator('xpath=ancestor::form').getByRole('button', {name:'Save occurrence review'}).click();
    await page.waitForURL('**#elavira-status-notice');
    await page.goto(base + '?view=report');
    const accepted = page.locator('details.elavira-accepted');
    assert.equal(await accepted.getAttribute('open'), null);
    assert.match(await accepted.locator('summary').innerText(), /Accepted findings \(1\)/);
    const order = await page.locator('.elavira-occurrences > li').evaluateAll(nodes => nodes.map(node => node.className));
    assert.deepEqual(order, ['elavira-occurrence-active','elavira-occurrence-addressed','elavira-occurrence-accepted']);
    await accepted.locator('summary').focus();
    await page.keyboard.press('Enter');
    assert.equal(await accepted.evaluate(node => node.open), true);
    assert.equal(await accepted.locator('.elavira-latest-note p').innerText(), 'Second occurrence note');
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement.tagName), 'A');
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'occurrence-status-2');
    await page.locator('#occurrence-status-2').selectOption('needs_review');
    await accepted.getByRole('button', {name:'Save occurrence review'}).click();
    await page.waitForURL('**#elavira-status-notice');
    await page.goto(base + '?view=report');
    assert.match(await accepted.locator('summary').innerText(), /Accepted findings \(0\)/);
    const second = page.locator('.elavira-occurrences > li').filter({has: page.locator('#occurrence-status-2')});
    assert.equal(await second.locator('.elavira-latest-note p').innerText(), 'Second occurrence note');
    const latest = 'Latest & plain text\n' + 'longword'.repeat(80);
    await page.locator('#occurrence-note-2').fill(latest);
    await second.getByRole('button', {name:'Save occurrence review'}).click();
    await page.waitForURL('**#elavira-status-notice');
    await page.goto(base + '?view=report');
    assert.equal(await second.locator('.elavira-latest-note p').innerText(), latest);
    assert.equal(await page.locator('#occurrence-note-2').inputValue(), '');
    assert.equal(await page.locator('.elavira-latest-note').count(), 2);
    await page.setViewportSize({width:320,height:800});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true);
    assert.equal(await page.locator('select,textarea').evaluateAll(nodes => nodes.every(node => node.labels.length)), true);
    const ids = await page.locator('[id]').evaluateAll(nodes => nodes.map(node => node.id));
    assert.equal(new Set(ids).size, ids.length);
    assert.deepEqual(failures, []);
    fs.mkdirSync('dist/ux-qa/regression', {recursive:true});
    await page.screenshot({path:'dist/ux-qa/regression/report-320.png',fullPage:true});
    fs.writeFileSync('dist/ux-qa/regression/browser-results.json', JSON.stringify({browser:'Microsoft Edge',passed:true,checks:['latest non-empty notes after reload','note-only save','status-only preserves note','empty note input','independent review','addressed ordering','collapsed accepted count','reconsider acceptance','keyboard disclosure and tab order','save focus and status region','320px reflow','control labels','unique IDs']},null,2));
    console.log('PASS: occurrence report browser workflow, keyboard, focus, labels, and 320px reflow');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
